import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { runCommand } from "./command-utils.mjs";

const migrationName = "20260731000000_baseline";
const migrationDir = resolve("prisma", "migrations", migrationName);
const migrationFile = resolve(migrationDir, "migration.sql");
const lockFile = resolve("prisma", "migrations", "migration_lock.toml");

if (existsSync(migrationFile) && !process.argv.includes("--force")) {
  throw new Error(`${migrationFile} ekziston. Mos e rigjenero baseline-in pa review; përdor --force vetëm para se migration-i të regjistrohet si applied.`);
}

mkdirSync(dirname(migrationFile), { recursive: true });

runCommand(
  process.platform === "win32" ? "npx.cmd" : "npx",
  [
    "prisma",
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema=prisma/schema.prisma",
    "--script",
    `--output=${migrationFile}`,
  ],
);

const sql = readFileSync(migrationFile, "utf8").trim();
if (!sql || !/CREATE TYPE|CREATE TABLE/i.test(sql)) {
  throw new Error("Baseline migration.sql nuk duket i plotë. File-i nuk u pranua.");
}

writeFileSync(lockFile, '# Please do not edit this file manually\nprovider = "postgresql"\n');

console.log(`Baseline u gjenerua: prisma/migrations/${migrationName}/migration.sql`);
console.log("Hapi tjetër: bëj backup, kontrollo drift-in dhe vetëm pastaj përdor db:baseline:resolve.");
